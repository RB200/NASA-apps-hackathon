"""Sunlight at each Artemis III candidate region, from NASA's LOLA average solar illumination map.

    python3 -B data_prep/moon_sunlight.py

Source: AVGVISIB_75S_120M_201608 (LRO-L-LOLA-4-GDR-V1.0, Mazarico et al. 2011, Icarus 211:1066,
doi:10.1016/j.icarus.2010.10.030), https://pgda.gsfc.nasa.gov/products/69
Each pixel is the fraction of time (hourly steps over an 18.6-year lunar nutation cycle) that any part
of the Sun's disc is above the local horizon, including shadows cast by surrounding terrain.
120 m/pixel, south polar stereographic, 75°S to the pole, so all 9 regions are covered.

Only the rows of each region's box are fetched (HTTP range requests), not the 116 MB file.
Writes frontend/sunlight.js (stats over each region's box from regions.js):
  mean   average sunlit fraction over the box
  best   sunniest pixel
  p90    90th percentile (the sunny high ground)
  dark   share of the box sunlit < 1% of the time (near-permanent shadow)
"""
from __future__ import annotations

import json
import math
import re
import struct
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGIONS_JS = ROOT / "frontend" / "regions.js"
OUT = ROOT / "frontend" / "sunlight.js"
BASE = "http://imbrium.mit.edu/EXTRAS/ILLUMINATION/IMG/AVGVISIB_75S_120M_201608"
R_MOON = 1_737_400.0


def label_value(label: str, key: str) -> float:
    return float(re.search(rf"^\s*{key}\s*=\s*([-\d.]+)", label, re.M).group(1))


def fetch(start: int, end: int) -> bytes:
    request = urllib.request.Request(BASE + ".IMG", headers={"Range": f"bytes={start}-{end}"})
    for attempt in range(5):
        try:
            with urllib.request.urlopen(request, timeout=60) as response:
                data = response.read()
            if len(data) == end - start + 1:
                return data
        except OSError:
            if attempt == 4:
                raise
    raise IOError("short read")


def main() -> None:
    label = urllib.request.urlopen(BASE + ".LBL", timeout=60).read().decode("utf-8", "replace")
    n = int(label_value(label, "LINE_SAMPLES"))
    px = label_value(label, "MAP_SCALE")
    line_off = label_value(label, "LINE_PROJECTION_OFFSET")
    sample_off = label_value(label, "SAMPLE_PROJECTION_OFFSET")
    scale = label_value(label, "SCALING_FACTOR")

    src = REGIONS_JS.read_text()
    regions = [(m[0], float(m[1]), float(m[2]), float(m[3]), float(m[4])) for m in re.findall(
        r"id: '([^']+)'.*?lat:\s*(-?[\d.]+), lon:\s*(-?[\d.]+), boxKm: \[(\d+), (\d+)\]", src)]

    out = {}
    for rid, lat, lon, w_km, h_km in regions:
        # Same polar stereographic convention as the LOLA DEMs (GDAL reading of the PDS label):
        # y points to 0° longitude (raster up); col = x/scale + SAMPLE_OFFSET, row = LINE_OFFSET - y/scale.
        rho = 2 * R_MOON * math.tan(math.radians(90 + lat) / 2)
        col = round(rho * math.sin(math.radians(lon)) / px + sample_off)
        row = round(line_off - rho * math.cos(math.radians(lon)) / px)
        hw, hh = round(w_km * 500 / px), round(h_km * 500 / px)
        with ThreadPoolExecutor(16) as pool:
            rows = list(pool.map(lambda r: fetch(2 * (r * n + col - hw), 2 * (r * n + col + hw) + 1),
                                 range(row - hh, row + hh + 1)))
        v = sorted(x * scale for data in rows for x in struct.unpack(f"<{len(data) // 2}h", data))
        out[rid] = {
            "mean": round(sum(v) / len(v), 3),
            "p90": round(v[int(0.9 * len(v))], 3),
            "best": round(v[-1], 3),
            "dark": round(sum(x < 0.01 for x in v) / len(v), 3),
        }
        print(f"{rid:22s} mean {out[rid]['mean']:.0%}  best {out[rid]['best']:.0%}  dark {out[rid]['dark']:.1%}")

    OUT.write_text(
        "// Generated by data_prep/moon_sunlight.py — do not edit by hand.\n"
        "// Fraction of time sunlit, over each region's box. NASA LRO LOLA average solar illumination\n"
        "// AVGVISIB_75S_120M (Mazarico et al. 2011), https://pgda.gsfc.nasa.gov/products/69\n"
        f"export const SUNLIGHT = {json.dumps(out, indent=2)};\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
